def taxonomy_table(table: pd.DataFrame) -> str:
    rows = [
        [
            tex(r["scenario"]),
            tex(r["agent"]),
            tex(r["action_type"]),
            tex(r["policy_decision"]),
            "yes" if r["executed"] else "no",
            str(int(r["runs"])),
        ]
        for _, r in table.iterrows()
    ]
    return booktabs(["Scenario", "Agent", "Action", "Policy", "Executed", "Runs"], rows, "lllllr")
